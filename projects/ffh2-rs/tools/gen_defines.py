#!/usr/bin/env python3
"""Generate crates/ffh-data/src/defines_gen.rs: a typed struct with one field per
global define (GlobalDefines.xml + GlobalDefinesAlt.xml + PythonCallbackDefines.xml),
plus any define the DLL/Python reads that is absent from XML (C++ returns 0).

Field name = lowercase define name. Int and text defines are i32 (text defines are
type names resolved to indices, like C++ SetPostGlobalsGlobalDefines); floats are f32.

Usage: tools/gen_defines.py [REF_DIR]
"""
import os, re, sys, glob

REF = sys.argv[1] if len(sys.argv) > 1 else "/home/user/ref"
HERE = os.path.dirname(os.path.abspath(__file__))
XML = os.path.normpath(os.path.join(HERE, "..", "data", "xml"))
OUT = os.path.normpath(os.path.join(HERE, "..", "crates", "ffh-data", "src", "defines_gen.rs"))
DLL = os.path.join(REF, "ffh2", "CvGameCoreDLL")
PY = os.path.join(REF, "ffh2", "Assets", "python")

DEF_RE = re.compile(r"<DefineName>(\w+)</DefineName>\s*<(\w+)>([^<]*)</\2>")

RUST_KW = {"type", "move", "loop", "match", "fn", "impl", "mod", "use", "ref", "self", "super", "static", "const"}


def main():
    kinds = {}
    order = []
    for f in ["GlobalDefines.xml", "GlobalDefinesAlt.xml", "PythonCallbackDefines.xml"]:
        s = open(os.path.join(XML, f), encoding="latin-1").read()
        s = re.sub(r"<!--.*?-->", "", s, flags=re.S)
        for m in DEF_RE.finditer(s):
            name, tag = m.group(1), m.group(2)
            kind = "f32" if tag.startswith("f") else "i32"
            if name not in kinds:
                order.append(name)
            kinds[name] = kind
    used_int, used_float = set(), set()
    srcs = glob.glob(os.path.join(DLL, "*.cpp")) + glob.glob(os.path.join(DLL, "*.h")) \
        + glob.glob(os.path.join(PY, "**", "*.py"), recursive=True)
    for p in srcs:
        s = open(p, encoding="latin-1").read()
        used_int.update(re.findall(r'getDefineINT\(\s*"(\w+)"', s))
        used_float.update(re.findall(r'getDefineFLOAT\(\s*"(\w+)"', s))
    missing = sorted((used_int | used_float) - set(kinds))
    for name in missing:
        order.append(name)
        kinds[name] = "f32" if name in used_float else "i32"

    lines = []
    lines.append("//! GENERATED by tools/gen_defines.py -- do not edit by hand.")
    lines.append("//! One field per global define. Text defines hold the resolved type index (-1 if none),")
    lines.append("//! exactly like C++ `GC.getDefineINT` after `SetPostGlobalsGlobalDefines`.\n")
    lines.append("use crate::defines::DefineMap;\n")
    lines.append("#[derive(Debug, Clone, Default)]")
    lines.append("pub struct Defines {")
    for name in order:
        field = name.lower()
        if field in RUST_KW:
            field += "_"
        note = "  // not in XML: C++ reads 0" if name in missing else ""
        lines.append(f"    pub {field}: {kinds[name]},{note}")
    lines.append("}\n")
    lines.append("impl Defines {")
    lines.append("    pub fn from_map(m: &DefineMap) -> Self {")
    lines.append("        Defines {")
    for name in order:
        field = name.lower()
        if field in RUST_KW:
            field += "_"
        getter = "float" if kinds[name] == "f32" else "int"
        lines.append(f'            {field}: m.{getter}("{name}"),')
    lines.append("        }")
    lines.append("    }")
    lines.append("}")
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {OUT}: {len(order)} defines ({len(missing)} referenced but absent from XML: {missing})")


if __name__ == "__main__":
    main()
